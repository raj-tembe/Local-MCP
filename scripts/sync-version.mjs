#!/usr/bin/env node
// Writes src/version.ts from package.json so the version reported to MCP clients and by
// `local-mcp --version` can never drift from the published version.
// Runs automatically as the npm "version" lifecycle step (see package.json), i.e. during
// `npm version <x.y.z>`, after package.json is bumped and before the release commit is created.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { version } = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const target = path.join(root, 'src', 'version.ts');

const contents = `// Generated by scripts/sync-version.mjs from package.json (run by \`npm version\`). Do not edit by hand.
export const VERSION = '${version}';
`;

if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== contents) {
  fs.writeFileSync(target, contents);
  console.log(`src/version.ts -> ${version}`);
} else {
  console.log(`src/version.ts already at ${version}`);
}
